	private PlotterMap currentMap;
	private int pointsx[];
	private int pointsy[];
	
	
	public PlotterCountries(){
	  currentMap=null;
	  pointsx=new int[countryNames.length];
	  pointsy=new int[countryNames.length];
	}
	
	private void calcPoints(Graphics g){
	  Point p=new Point();
	  FontMetrics fm = g.getFontMetrics(g.getFont());
	  int size;
	  for(int i=0;i<countryNames.length;i++){
	    currentMap.plot(lats[i],lons[i],p);
	    size=(fm.stringWidth(countryNames[i]))/2; // center the text on the area
	    pointsx[i]=p.x-size;
	  pointsy[i]=p.y;
	  }
	}
	public void paint(Graphics g,PlotterMap map){
	  if(map!=currentMap){
	    currentMap=map;
	    calcPoints(g);
	  }     
	  for(int i=0;i<countryNames.length;i++){
	    g.setColor(Color.BLACK);
	    g.drawString(countryNames[i],pointsx[i]-1,pointsy[i]-1);
	    //g.drawString(countryNames[i],pointsx[i]+1,pointsy[i]+1);
	    g.setColor(Color.GRAY);
	    g.drawString(countryNames[i],pointsx[i],pointsy[i]);
	  }
	}

